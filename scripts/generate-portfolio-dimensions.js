import fs from 'node:fs/promises';
import path from 'node:path';
import imageSize from 'image-size';
import { fileURLToPath } from 'node:url';

// Get the directory name in an ES module context
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PORTFOLIO_BASE_DIR = path.resolve(__dirname, '..', 'static/images/portfolio');
const OUTPUT_DIR = path.resolve(__dirname, '..', 'src/lib/data');
const WIDTH_DIR_REGEX = /^w(\d+)$/; // Matches directories like w320, w640 etc.

async function generateDimensionsForWidth(widthDir, width) {
  const inputDir = path.join(PORTFOLIO_BASE_DIR, widthDir);
  const outputFilename = `portfolio-dimensions-w${width}.ts`;
  const outputFile = path.join(OUTPUT_DIR, outputFilename);
  console.log(`Generating dimensions for ${widthDir} -> ${outputFilename}...`);

  const dimensionsMap = {};

  try {
    const files = await fs.readdir(inputDir);

    for (const file of files) {
      const ext = path.extname(file).toLowerCase();
      // Process common image formats found within width directories
      if (!['.jpg', '.jpeg', '.png', '.webp'].includes(ext)) {
        console.log(`  Skipping non-image file in ${widthDir}: ${file}`);
        continue;
      }

      const filePath = path.join(inputDir, file);
      try {
        const buffer = await fs.readFile(filePath);
        const dimensions = imageSize(buffer);
        if (dimensions.width && dimensions.height) {
          dimensionsMap[file] = { width: dimensions.width, height: dimensions.height };
          // console.log(`    Processed ${file}: ${dimensions.width}x${dimensions.height}`);
        } else {
          console.warn(`    Could not get dimensions for ${file} in ${widthDir}`);
        }
      } catch (err) {
        console.error(`    Error processing file ${file} in ${widthDir}:`, err.message);
      }
    }

    // Generate TypeScript file content
    let tsContent = `// Generated by scripts/generate-portfolio-dimensions.js for width ${width}\n`;
    tsContent += '// Do not edit this file manually!\n\n';
    tsContent += `export const dimensionsMapW${width} = {`;

    const entries = Object.entries(dimensionsMap);
    if (entries.length === 0) {
      console.log(`  No images found or processed in ${widthDir}.`);
    } else {
      for (let i = 0; i < entries.length; i++) {
          const [filename, dims] = entries[i];
          const escapedFilename = JSON.stringify(filename);
          tsContent += `\n  ${escapedFilename}: { width: ${dims.width}, height: ${dims.height} }`;
          if (i < entries.length - 1) {
              tsContent += ',';
          }
      }
    }

    tsContent += '\n} as const;\n';
    tsContent += `\nexport type PortfolioImageFilenameW${width} = keyof typeof dimensionsMapW${width};\n`;

    // Write the TypeScript content to the file
    await fs.writeFile(outputFile, tsContent);

    console.log(`  Successfully wrote dimensions map to ${outputFilename}`);

  } catch (error) {
    // Handle cases where the width directory might not exist
    if (error.code === 'ENOENT') {
      console.warn(`  Directory ${widthDir} not found. Skipping.`);
    } else {
      console.error(`  Error processing directory ${widthDir}:`, error);
    }
    // Optionally, still write an empty file?
    // Or just skip file creation if dir doesn't exist/fails
  }
}

async function generateAllDimensions() {
  console.log('Scanning portfolio base directory:', PORTFOLIO_BASE_DIR);
  try {
    // Ensure base output directory exists
    await fs.mkdir(OUTPUT_DIR, { recursive: true });

    const entries = await fs.readdir(PORTFOLIO_BASE_DIR, { withFileTypes: true });
    let foundWidthDirs = 0;

    for (const entry of entries) {
      if (entry.isDirectory()) {
        const match = entry.name.match(WIDTH_DIR_REGEX);
        if (match) {
          const width = parseInt(match[1], 10);
          await generateDimensionsForWidth(entry.name, width);
          foundWidthDirs++;
        }
      }
    }
    if (foundWidthDirs === 0) {
        console.warn(`No width-specific directories (e.g., w320, w640) found in ${PORTFOLIO_BASE_DIR}`);
    }
    console.log('Finished generating all portfolio dimensions.');
  } catch (error) {
     if (error.code === 'ENOENT') {
       console.error(`Error: Portfolio base directory not found at ${PORTFOLIO_BASE_DIR}`);
     } else {
       console.error('Error generating portfolio dimensions:', error);
     }
    process.exit(1);
  }
}

generateAllDimensions(); 